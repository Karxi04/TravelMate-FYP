"""Prepare, or explicitly apply, the create-only private Penang expansion."""
import argparse
from collections import Counter, defaultdict
from datetime import datetime
from hashlib import sha256
import json
import os
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from scripts.plan_penang_fyp_reviews import build_plan as build_base_plan
from services.fyp_reviews import (
    DATASET_PATH, EXPANSION_COLLECTION, EXPANSION_COUNT, MANIFEST_PATH, PROJECT, REVIEW_COUNT,
)
from services.review_destination import review_destination_id
from services.review_service import approved_reviews, review_id, screen_submission, valid_review

FIXTURE = Path(__file__).resolve().parents[1] / 'tests/fixtures/penang_fyp_review_expansion.json'
APPROVED_BASE_SHA256 = '1d5758755f5f6abf315597392c488dc8845cdb4ce4b20591bc53111446be5f1a'


def build_plan():
    base = build_base_plan()['documents']
    destinations = base[DATASET_PATH]['destinations']
    contents = FIXTURE.read_text(encoding='utf-8').encode('utf-8')
    fixture = json.loads(contents)
    if fixture.get('synthetic') is not True:
        raise ValueError('Expected synthetic review fixtures.')
    documents = {}
    screening_counts = Counter()
    comments = {row['comment'].strip().casefold() for path, row in base.items() if path != DATASET_PATH}
    names = set()
    for example in fixture['reviews']:
        destination = review_destination_id(example['destinationId'])
        place = destinations[destination]
        name = example['reviewer']
        date = example['submittedAt']
        payload = {'destinationId': destination, 'destinationName': place['title'],
                   'rating': example['rating'], 'comment': example['comment']}
        comment = payload['comment'].strip().casefold()
        if not valid_review(payload) or comment in comments or name in names or not datetime.fromisoformat(date).tzinfo:
            raise ValueError(f'Invalid or duplicate review for {place["title"]}: {name}.')
        comments.add(comment)
        names.add(name)
        decision = screen_submission(payload['comment'], payload['rating'])
        risk = decision['screening']['risk']
        if risk != example['expectedRisk']:
            raise ValueError(f'{name} at {place["title"]} screened as {risk}, expected {example["expectedRisk"]}.')
        screening_counts[risk] += 1
        # Fictional dates make the generated bytes reproducible. FR10 determines the outcome.
        decision['screening']['screenedAt'] = date
        decision['moderationDecision']['at'] = date
        author = 'penang_v2_' + sha256(name.casefold().encode()).hexdigest()[:24]
        fid = review_id(author, destination)
        documents[f'{DATASET_PATH}/{EXPANSION_COLLECTION}/{fid}'] = {
            **payload, **decision, 'synthetic': True, 'travellerId': author,
            'travellerName': name, 'submittedAt': date, 'updatedAt': date,
        }
    if screening_counts != {'low': 60, 'flagged': 6, 'uncertain': 2} or len(documents) != EXPANSION_COUNT:
        raise ValueError(f'Unexpected screening totals: {dict(screening_counts)}.')
    groups = defaultdict(list)
    original_reviews = [row for path, row in base.items() if path != DATASET_PATH]
    for row in [*original_reviews, *documents.values()]:
        groups[row['destinationId']].append(row)
    summaries = {}
    for identity, rows in groups.items():
        approved = approved_reviews(rows)
        summaries[identity] = {'approved': len(approved),
                               'average': round(sum(row['rating'] for row in approved) / len(approved), 1)}
    documents[f'{DATASET_PATH}/{MANIFEST_PATH}'] = {
        'version': 2, 'synthetic': True, 'baseReviewCount': REVIEW_COUNT,
        'fixtureSha256': sha256(contents).hexdigest(),
        'reviewIds': sorted(path.rsplit('/', 1)[-1] for path in documents),
    }
    return {'project': PROJECT, 'database': '(default)', 'operation': 'create_only',
            'approvedBasePlanSha256': APPROVED_BASE_SHA256,
            'screeningCounts': dict(screening_counts), 'initialDestinationSummaries': summaries,
            'documents': documents}


def plan_bytes():
    return (json.dumps(build_plan(), ensure_ascii=True, indent=2, sort_keys=True) + '\n').encode()


def apply_plan(plan, approved_base_path):
    """All-or-nothing creation with an exact replay treated as a no-op."""
    from dotenv import load_dotenv
    from firebase_admin import firestore as firebase_firestore
    from google.cloud import firestore
    from firebase_service import init_firebase

    load_dotenv(Path(__file__).resolve().parents[1] / '.env')
    if os.getenv('FIRESTORE_EMULATOR_HOST'):
        raise ValueError('The approved live plan cannot run against an emulator.')
    base_bytes = approved_base_path.read_bytes()
    if sha256(base_bytes).hexdigest() != APPROVED_BASE_SHA256:
        raise ValueError('The legacy plan does not match the original approved SHA-256.')
    base = json.loads(base_bytes.decode('utf-8-sig'))['documents']
    app = init_firebase()
    if app.project_id != PROJECT:
        raise ValueError('Incorrect Firestore project.')
    db = firebase_firestore.client(app, database_id='(default)')
    return _create_expansion(db, base, plan['documents'], firestore)


def _create_expansion(db, base, added, firestore):
    root = db.document(DATASET_PATH)
    manifest = db.document(f'{DATASET_PATH}/{MANIFEST_PATH}')

    @firestore.transactional
    def commit(transaction):
        originals = {root.path: root.get(transaction=transaction).to_dict()}
        originals.update({snap.reference.path: snap.to_dict() for snap in
                          root.collection('reviews').limit(REVIEW_COUNT + 1).stream(transaction=transaction)})
        if originals != base:
            raise ValueError('The original dataset does not match the approved import.')
        present = {snap.reference.path: snap.to_dict() for snap in
                   root.collection(EXPANSION_COLLECTION).limit(EXPANSION_COUNT + 1).stream(transaction=transaction)}
        version = manifest.get(transaction=transaction)
        if version.exists:
            present[manifest.path] = version.to_dict()
        if present:
            if present == added:
                return 'already_applied'
            raise ValueError('Expansion paths are already occupied or partially present.')
        # Readers only select this collection when the same transaction creates its manifest.
        for path, data in added.items():
            transaction.create(db.document(path), data)
        return 'created'

    return commit(db.transaction())


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, help='Write the proposed plan without contacting Firestore.')
    parser.add_argument('--apply', type=Path, help='Path to the separately approved expansion plan.')
    parser.add_argument('--sha256', help='The separately approved expansion digest.')
    parser.add_argument('--approved-base', type=Path, help='Original frozen 37-create plan.')
    args = parser.parse_args()
    if args.apply:
        if not args.sha256 or not args.approved_base or args.output:
            parser.error('--apply requires --sha256 and --approved-base and forbids --output.')
        data = args.apply.read_bytes()
        if sha256(data).hexdigest() != args.sha256 or data != plan_bytes():
            raise SystemExit('The file does not match the approved digest and current deterministic plan.')
        print(apply_plan(json.loads(data), args.approved_base))
    elif args.output:
        data = plan_bytes()
        args.output.write_bytes(data)
        print(sha256(data).hexdigest())
    else:
        parser.error('Choose --output to prepare the plan or --apply to apply an explicitly approved plan.')
