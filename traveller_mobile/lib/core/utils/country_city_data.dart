  /// Returns the suggested cities for the specified country.
  /// If [country] is null or empty, returns an empty list.
  /// Matches case-insensitively against the known country names.
  static List<String> getCitiesForCountry(String? country) {
    if (country == null) return const [];
    final trimmed = country.trim().toLowerCase();
    if (trimmed.isEmpty) return const [];
    for (final entry in countryCities.entries) {
      if (entry.key.toLowerCase() == trimmed) {
        return entry.value;
      }
    }
    return const [];
  }

  /// Checks if [city] belongs to the preset city suggestions of [country].
  static bool isCityInCountry(String city, String country) {
    final cities = getCitiesForCountry(country);
    final target = city.trim().toLowerCase();
    return cities.any((c) => c.toLowerCase() == target);
  }
